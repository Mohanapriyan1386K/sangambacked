const router = require('express').Router();
const c = require('../controllers/eventController');
const wrap = require('../utils/asyncHandler');
const { authenticate, authorize } = require('../middleware/auth');
const { validateId, validateBody } = require('../middleware/validate');
router.use(authenticate);
router.get('/', authorize('events:view'), wrap(c.list));
router.post('/', authorize('events:create'), validateBody(['title', 'description', 'startsAt', 'endsAt', 'venue']), wrap(c.create));
router.get('/organizers', authorize('events:view'), wrap(c.organizers));
router.post('/organizers', authorize('events:create'), validateBody(['name']), wrap(c.createOrganizer));
router.patch('/organizers/:id', authorize('events:edit'), validateId, wrap(c.updateOrganizer));
router.get('/:id/donations', authorize('donations:view'), validateId, wrap(c.donations));
router.post('/:id/donations', authorize('donations:create'), validateId, validateBody(['amount']), wrap(c.createDonation));
router.post('/donations/:id/void', authorize('donations:edit'), validateId, validateBody(['reason']), wrap(c.voidDonation));
router.get('/:id/expenses', authorize('expenses:view'), validateId, wrap(c.expenses));
router.post('/:id/expenses', authorize('expenses:create'), validateId, validateBody(['category', 'amount']), wrap(c.createExpense));
router.get('/:id', authorize('events:view'), validateId, wrap(c.get));
router.patch('/:id', authorize('events:edit'), validateId, wrap(c.update));
router.delete('/:id', authorize('events:delete'), validateId, wrap(c.remove));
module.exports = router;
